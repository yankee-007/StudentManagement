    def test_individual_mixed_content_edit_and_sent_immutable(self):
        with seeded(1) as b, tempfile.TemporaryDirectory() as folder:
            file=Path(folder)/'attachment.txt'
            # A test fixture generated by the test, not an application export.
            file.write_text('test attachment',encoding='utf-8')
            g=b.groupCenter
            initial=[dict(type='text',text='{姓名}原话术')]
            self.assertTrue(g.createStructured('测试','甲\n乙',initial))
            first,second=g.rows
            list_id=g.selected['id']
            self.assertTrue(g.prepare('',{}))
            updated=[dict(type='text',text='甲的独立话术'),dict(type='file',path=str(file)),dict(type='text',text='文件说明')]
            self.assertTrue(g.saveRecipientContent(list_id,first['id'],updated))
            self.assertFalse(g.preview)
            self.assertIsNone(g._confirmation)
            saved=json.loads(g.rows[0]['content'])
            self.assertEqual([item['text'] if item['type']=='text' else item['path'] for item in saved],
                             [item['text'] if item['type']=='text' else item['path'] for item in updated])
            self.assertTrue(all(item.get('personal_override') for item in saved))
            self.assertEqual(json.loads(g.rows[1]['content']),[dict(type='text',text='乙原话术',template='{姓名}原话术')])
            self.assertEqual([c[1] for c in g.pendingModel.columns][:4],['名字','话术1','文件1','话术2'])
            task=g.store.plan(list_id)[0]
            attempt=g.store.claim(list_id,task)
            g.store.finish(list_id,task,attempt,states.SENT,'测试桩，无实际发送')
            g.refresh()
            self.assertEqual((g.pendingCount,g.sentCount),(1,1))
            self.assertFalse(g.saveRecipientContent(list_id,first['id'],initial))
            self.assertFalse(g.saveRecipientContent(list_id+1,second['id'],initial))
            self.assertTrue(g.saveContent(list_id,[dict(type='text',text='统一新话术')]))
            protected_items=json.loads(g.rows[0]['content'])
            self.assertEqual([item['text'] if item['type']=='text' else item['path'] for item in protected_items],
                             [item['text'] if item['type']=='text' else item['path'] for item in updated])
            self.assertTrue(all(item.get('personal_override') for item in protected_items))
            self.assertEqual(g.rows[1]['message'],'统一新话术')
            reopened=GroupStore(g.store.path)
            reopened_items=json.loads(reopened.rows(list_id)[0]['content'])
            self.assertTrue(all(item.get('personal_override') for item in reopened_items))

    def test_copy_batch_templates_bulk_protection_mixed_fields_and_history_isolation(self):
        with seeded(2) as b, tempfile.TemporaryDirectory() as folder:
            attachment=Path(folder)/'lesson.txt'
            attachment.write_text('temporary fixture',encoding='utf-8')
            b.repo.update_profile_field('P2026169001A','微信','是')
            b.repo.update_profile_field('P2026169002A','微信','否')
            p,g=b.profilesModule,b.groupCenter
            fields=[dict(type='text',text='{姓名}-{微信}'),dict(type='file',path=str(attachment))]
            self.assertTrue(g.createFromProfiles('可复制名单',fields,p.recipientKeys),g.status)
            list_id=g.selected['id']
            first,second=g.rows

            # A cell-level edit is marked and default whole-column updates preserve it.
            self.assertTrue(g.saveRecipientContent(list_id,first['id'],[dict(type='text',text='个人话术'),dict(type='file',path=str(attachment))]),g.status)
            self.assertTrue(g.bulkField(list_id,0,dict(type='text',text='{姓名}-统一-{微信}'),False),g.status)
            self.assertIn('个人话术',g.rows[0]['message'])
            second_learning=json.loads(second['learning_data'])
            second_wechat=second_learning['profile_fields']['微信']
            self.assertTrue(g.rows[1]['message'].startswith(f"{second['name']}-统一-{second_wechat}"))
            self.assertTrue(json.loads(g.rows[0]['content'])[0].get('personal_override',False))

            # Newly appended text follows the file column, preserving mixed send order.
            self.assertTrue(g.appendField(dict(type='text',text='补充-{姓名}')),g.status)
            second_items=json.loads(g.store.rows(list_id)[1]['content'])
            self.assertEqual([x['type'] for x in second_items],['text','file','text'])
            self.assertIn('补充-学员2',second_items[2]['text'])
            g.store.move_field(list_id,2,-1)
            self.assertEqual([x['type'] for x in json.loads(g.store.rows(list_id)[1]['content'])],['text','text','file'])
            g.store.move_field(list_id,1,1)
            self.assertEqual([x['type'] for x in json.loads(g.store.rows(list_id)[1]['content'])],['text','file','text'])
            g.store.remove_field(list_id,2)
            self.assertEqual([x['type'] for x in json.loads(g.store.rows(list_id)[1]['content'])],['text','file'])
            g.store.append_field(list_id,dict(type='text',text='补充-{姓名}'))

            # Record one mocked completion directly through the store, never using the desktop sender.
            task=next(t for t in g.store.plan(list_id) if t['name']=='学员2')
            attempt=g.store.claim(list_id,task)
            self.assertIsNotNone(attempt)
            g.store.finish(list_id,task,attempt,states.SENT,'临时验证：未调用实际发送')
            sent_before=json.loads(next(r for r in g.store.rows(list_id) if r['name']=='学员2')['content'])

            # Re-render the original template against current profile values in a separate fresh batch.
            b.repo.update_profile_field('P2026169001A','微信','否')
            b.repo.update_profile_field('P2026169002A','微信','是')
            old_records=len([1 for _ in g.store.rows(list_id)])
            self.assertTrue(g.copyList('复制的新名单',True),g.status)
            copied_id=g.selected['id']
            self.assertNotEqual(copied_id,list_id)
            self.assertTrue(all(r['state']=='待发送' for r in g.store.rows(copied_id)))
            copied={r['name']:json.loads(r['content']) for r in g.store.rows(copied_id)}
            latest_first=b.repo.get('P2026169001A')['profile_fields']['微信']
            latest_second=b.repo.get('P2026169002A')['profile_fields']['微信']
            self.assertEqual(copied['学员1'][0]['text'],'个人话术')
            self.assertTrue(copied['学员1'][0].get('personal_override'))
            self.assertEqual([x['type'] for x in copied['学员1']],['text','file','text'])
            self.assertEqual(copied['学员2'][0]['text'],f"学员2-统一-{latest_second}")
            # Later edits only affect the still-pending recipient; sent history remains byte-for-byte frozen.
            self.assertEqual(g.store.bulk_field(list_id,0,dict(type='text',text='后续-{姓名}'),override_personal=True),1)
            self.assertFalse(json.loads(next(r for r in g.store.rows(list_id) if r['name']=='学员1')['content'])[0].get('personal_override',False))
            g.store.append_field(list_id,dict(type='text',text='新字段'))
            sent_after=json.loads(next(r for r in g.store.rows(list_id) if r['name']=='学员2')['content'])
            self.assertEqual(sent_after,sent_before)
            with g.store.connect() as conn:
                self.assertEqual(conn.execute('SELECT count(*) FROM attempts WHERE recipient_id IN (SELECT id FROM recipients WHERE list_id=?)',(list_id,)).fetchone()[0],1)
                self.assertEqual(conn.execute('SELECT count(*) FROM attempts WHERE recipient_id IN (SELECT id FROM recipients WHERE list_id=?)',(copied_id,)).fetchone()[0],0)
            self.assertEqual(len(g.store.rows(list_id)),old_records)
            self.assertTrue(g.copyList('只复制名单',False),g.status)
            self.assertTrue(all(json.loads(r['content'])==[] and r['state']=='待发送' for r in g.rows))

