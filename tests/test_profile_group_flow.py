    def test_multiselect_blank_counts_conditions_and_sort(self):
        with seeded(3) as b:
            p=b.profilesModule
            b.repo.update_profile_field('P2026169002A','微信','否')
            b.repo.update_profile_field('P2026169003A','微信','')
            b.repo.update_profile_field('P2026169001A','QQ','是')
            p.refresh()
            index=next(i for i,c in enumerate(p.tableModel.columns) if c[0]=='profile:微信')
            self.assertEqual({o['value']:o['count'] for o in p.columnFilterInfo(index)['options']},{'':1,'是':1,'否':1})
            p.setColumnFilter('profile:微信','values',['是',''],'')
            self.assertEqual(p.visibleCount,2)
            p.setColumnFilter('profile:QQ','empty',[],'')
            self.assertEqual([r['name'] for r in p.tableModel.rows],['学员3'])
            p.setColumnFilter('profile:QQ','clear',[],'')
            p.sortField('name',True)
            self.assertEqual([r['name'] for r in p.tableModel.rows],['学员3','学员1'])
            p.setColumnFilter('profile:微信','values',[],'')
            self.assertEqual(p.visibleCount,0)
            self.assertEqual(len(p.columnFilterInfo(index)['options']),3)
            p.clearFilters()
            p.setColumnFilter('name','contains',[],'2')
            self.assertEqual(p.selected['name'],'学员2')

