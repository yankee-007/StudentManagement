    def test_single_cell_change_keeps_other_cells_and_table_stable(self):
        with seeded(1) as b:
            g=b.groupCenter
            self.assertTrue(g.createStructured('逐格编辑','甲\n乙',[
                dict(type='text',text='首句-{姓名}'),dict(type='text',text='第二句')]))
            list_id=g.selected['id'];recipient_id=g.rows[0]['id']
            resets=[]
            g.pendingModel.modelReset.connect(lambda:resets.append(1))
            g._notice='仅更新状态提示';g.changed.emit()
            self.assertEqual(resets,[])
            self.assertTrue(g.saveRecipientField(list_id,recipient_id,0,dict(type='text',text='单独-{姓名}')),g.status)
            self.assertEqual(resets,[])
            first=json.loads(g.rows[0]['content']);second=json.loads(g.rows[1]['content'])
            self.assertEqual(first[0]['text'],'单独-甲')
            self.assertTrue(first[0]['personal_override'])
            self.assertEqual(first[1]['text'],'第二句')
            self.assertFalse(first[1].get('personal_override',False))
            self.assertEqual(second[0]['text'],'首句-乙')
            self.assertNotIn('个人修改',g.pendingModel.get(0)['message_0'])
            reopened=GroupStore(g.store.path)
            self.assertEqual(json.loads(reopened.rows(list_id)[0]['content']),first)

